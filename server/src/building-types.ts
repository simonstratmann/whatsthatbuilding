/** What a walker would call a building of a type the table doesn't know. */
const GENERIC_TYPE = "Gebäude";

/** The building type for an AdV function code, e.g. "31001_1010" → "Wohnhaus". */
export function buildingTypeOf(functionCode: string): string {
  return TYPES[functionCode.replace(/^31001_/, "")] ?? GENERIC_TYPE;
}
